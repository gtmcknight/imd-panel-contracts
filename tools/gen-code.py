#!/usr/bin/env python3
"""Writes the four PanelCode contracts from art/imd-panel.js.gz: each one's deployed bytecode is a STOP byte and
then up to 24,575 bytes of the gzipped drawing code, in order. The same .gz gives the same files."""
import hashlib, os, sys
here = os.path.dirname(os.path.abspath(__file__))
gz = open(os.path.join(here, "..", "art", "imd-panel.js.gz"), "rb").read()
CHUNK, N = 24575, 4
assert len(gz) <= CHUNK * N, f"code is {len(gz)} bytes, more than {N} contracts hold"
for i in range(N):
    part = gz[i * CHUNK:(i + 1) * CHUNK]
    src = f"""// SPDX-License-Identifier: MIT
// Generated by tools/gen-code.py from art/imd-panel.js.gz. Do not edit.
pragma solidity 0.8.28;

/// @title PanelCode{i}
/// @notice Part {i + 1} of 4 of the gzipped panel drawing code, {len(part)} bytes, kept as this contract's bytecode after a
/// leading STOP byte, so it can never run and never change. PanelRenderer reads it with EXTCODECOPY.
contract PanelCode{i} {{
    constructor() {{
        bytes memory code = hex"00{part.hex()}";
        assembly {{
            return(add(code, 32), mload(code))
        }}
    }}
}}
"""
    open(os.path.join(here, "..", "src", "code", f"PanelCode{i}.sol"), "w").write(src)
print(f"{len(gz)} bytes in {N} contracts")
